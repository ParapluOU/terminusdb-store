//! The public "wire" vocabulary of a layer BGP and how a plan becomes a bound statement.
//!
//! This module has two jobs. First, it defines the DATA a caller hands in and gets back: an
//! atom ([`LayerBgpAtom`]) is one triple pattern with variables/constants/optional range; a
//! plan ([`LayerBgpPlan`]) is a conjunction of atoms plus the join steps linking them; and
//! the various proof/result structs and result-value types describe what comes out. Second,
//! it validates a plan into a legal shape and binds the whole public statement into the
//! Fiat–Shamir transcript ([`bind_layer_bgp_statement`]) — the step that pins every atom,
//! constant, range, source, and join into the challenges, so the proof can only be for the
//! exact query asked. None of this is cryptography; it is the careful bookkeeping the crypto
//! layers depend on being exact.

use super::*;

/// One term (subject or object) of a layer BGP atom: a query VARIABLE (kept as an
/// output column) or a CONSTANT authenticated against the layer's node/value dictionary.
/// `NodeConstant` is a node IRI (valid in the subject or object position); `ValueConstant`
/// is a typed literal (valid in the object position only). A node IRI resolves through the
/// SAME node/value id whether it appears as a subject or an object constant.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AtomTerm {
    Variable,
    NodeConstant(Vec<u8>),
    ValueConstant(CanonicalDatatype, Vec<u8>),
}

/// Store ID namespace for an authenticated result column. Predicate dictionary IDs and
/// node/value dictionary IDs are independent even when their numeric field values match.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ResultIdNamespace {
    /// A node/value dictionary id (a subject or object binding), resolved via the node/value catalog.
    NodeValue,
    /// A predicate dictionary id, resolved via the (independent) predicate catalog.
    Predicate,
    /// A nonnegative integral `xsd:decimal` generated by the authenticated statement,
    /// encoded directly as a canonical u64 field rather than a Store dictionary ID.
    GeneratedDecimalU64,
    /// An integral signed `xsd:decimal` generated by the authenticated statement,
    /// encoded canonically as `v` for nonnegative values and `-abs(v)` in the scalar
    /// field for negative values. This is never a Store dictionary ID.
    GeneratedDecimalI64,
}

/// Authoritative interpretation of one public result column. Nullability is a query-plan
/// property, never inferred from a delivered field value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ResultColumnDescriptor {
    pub namespace: ResultIdNamespace,
    pub nullable: bool,
}

/// Canonical public result value. `Null` is distinct from every Store dictionary object
/// and is represented by field zero only in a nullable result column.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum CanonicalResultValue {
    Object(CanonicalObject),
    GeneratedDecimalU64(u64),
    GeneratedDecimalI64(i64),
    Null,
}

/// Canonical field encoding for a generated signed decimal. Zero is a valid nonnull
/// result; nullability is carried only by [`ResultColumnDescriptor`].
pub fn generated_decimal_i64_field(value: i64) -> ArkFr {
    if value >= 0 {
        ArkFr::from_u64(value as u64)
    } else {
        -ArkFr::from_u64(value.unsigned_abs())
    }
}

/// Decode the exact field image used by generated nonnegative decimal outputs.
/// Reject field elements outside the canonical u64 image instead of truncating.
pub fn generated_decimal_u64_value(field: ArkFr) -> io::Result<u64> {
    let value = field.0.into_bigint();
    let limbs = value.as_ref();
    if limbs[1..].iter().any(|limb| *limb != 0) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "generated decimal is outside canonical u64 range",
        ));
    }
    Ok(limbs[0])
}

/// Decode the exact field image used by generated signed decimal outputs (the inverse of
/// [`generated_decimal_i64_field`]): a nonnegative value is its canonical u64 image, a negative
/// value is `-abs(v)` in the scalar field. Reject a field element outside the canonical i64
/// image (in either the positive or the sign-flipped-magnitude range) instead of truncating.
pub fn generated_decimal_i64_value(field: ArkFr) -> io::Result<i64> {
    if field.is_zero() {
        return Ok(0);
    }
    let positive = field.0.into_bigint();
    if positive.as_ref()[1..].iter().all(|limb| *limb == 0)
        && positive.as_ref()[0] <= i64::MAX as u64
    {
        return Ok(positive.as_ref()[0] as i64);
    }
    let magnitude = (-field).0.into_bigint();
    let magnitude = magnitude.as_ref();
    if magnitude[1..].iter().all(|limb| *limb == 0)
        && (1..=(1u64 << 63)).contains(&magnitude[0])
    {
        return Ok(if magnitude[0] == 1u64 << 63 {
            i64::MIN
        } else {
            -(magnitude[0] as i64)
        });
    }
    Err(invalid(
        "generated signed decimal result is outside canonical i64 range",
    ))
}

/// One numeric comparison `op c`: a [`RangeOp`] plus an order-preserving-encoded constant.
/// Used as the SECOND, half-open bound of an [`ObjectRangeSpec`] (the datatype discriminant
/// and the bit-width are shared with the primary bound, so they are not repeated here).
#[derive(Clone, Debug)]
pub struct ObjectRangeBound {
    pub op: RangeOp,
    pub c: ArkFr,
}

/// A numeric RANGE filter on an atom's VARIABLE object: `?o op c`, where the object's
/// dict-authenticated typed value (of datatype discriminant `T`) is compared to the
/// PUBLIC order-preserving-encoded constant `c`. `b_bits` is the range gadget's
/// bit-width (`64` for the store's `<= 8`-byte numerics — see [`crate::proof::range`]). Bound
/// into the layer BGP statement so the whole comparison is pinned.
#[derive(Clone, Debug)]
pub struct ObjectRangeSpec {
    /// The comparison operator (`<`, `<=`, `>`, `>=`).
    pub op: RangeOp,
    /// The datatype discriminant `T` the object must match (a `CanonicalDatatype as u64`
    /// tag, or the Node tag), as a field element.
    pub datatype: ArkFr,
    /// The order-preserving-encoded comparison constant `c`, as a field element.
    pub c: ArkFr,
    /// The range gadget's bit-width (`64` for the store's fixed-width numerics).
    pub b_bits: usize,
    /// Optional second bound over the same datatype and bit-width. This represents an
    /// intersection, e.g. `V >= low AND V < high` for WOQL's half-open ranges.
    pub second: Option<ObjectRangeBound>,
}

/// Public object-kind constraint for a layer BGP atom. Store node IRIs and literal
/// values share the object dictionary, so this constraint is authenticated against
/// the dictionary datatype tag while preserving the original Store object ID.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ObjectKindFilter {
    Any,
    Node,
    Literal,
}

/// One atom of a layer BGP. A constant predicate IRI is authenticated by the layer's
/// predicate dictionary; a predicate variable retains the root-bound materialized P
/// column directly. The subject/object may each be a
/// VARIABLE (a kept output column) or a CONSTANT (authenticated against the layer's
/// node/value dictionary and folded into the atom filter). A fully-ground atom is
/// represented internally by the filter gadget's authenticated UNIT column and is
/// accepted alone or in an all-ground conjunction. An optional `object_range`
/// adds a numeric RANGE filter on the object — valid ONLY when the object is a
/// `Variable` (a ranged object is a kept variable, never a constant). Constraints
/// (enforced at prove AND verify): the subject may not be a `ValueConstant` (literals
/// never occupy the subject position), and an `object_range` requires a `Variable`
/// object with a valid bit-width.
#[derive(Clone, Debug)]
pub struct LayerBgpAtom {
    pub subject: AtomTerm,
    /// Empty for a predicate variable; otherwise the constant predicate IRI.
    pub predicate_term: Vec<u8>,
    pub predicate_variable: bool,
    pub object: AtomTerm,
    pub object_range: Option<ObjectRangeSpec>,
    /// Restrict a variable object to nodes, literals, or leave it unconstrained.
    pub object_kind: ObjectKindFilter,
    /// Require the subject and object variables to be equal within each selected row.
    pub subject_object_equal: bool,
    /// Which committed `(S, P, O)` column set THIS atom reads: the layer's complete
    /// materialized head view (the pre-delta default, and the value that keeps every legacy
    /// plan byte-identical), or the layer's own additions / removals delta file. Making the
    /// source PER-ATOM (rather than one per plan) is what admits a CROSS-SOURCE join, e.g.
    /// `AddedTriple(?x, p, ?y) & Triple(?y, q, ?z)` (additions ⋈ materialized) or
    /// additions ⋈ removals: all three sets share the SAME predicate/node-value dictionaries,
    /// so their dictionary IDs are directly comparable and the audited join gadget joins them
    /// unchanged. The source is bound TWO ways so a prover cannot relabel it: it is part of the
    /// plan wire image (hence `plan_digest`) that the verifier reconstructs from its own trusted
    /// query, AND it is domain-separated in the Fiat–Shamir transcript. `Materialized` emits NO
    /// extra transcript bytes when it matches the plan default, so pre-delta / uniform proofs
    /// stay byte-identical.
    pub source: ColumnSource,
}

impl LayerBgpAtom {
    /// The classic all-variable atom `t(?s, <predicate_term>, ?o)`: both subject and
    /// object are query variables (the two kept output columns), no object range, reading the
    /// complete materialized head view.
    pub fn all_variables(predicate_term: Vec<u8>) -> Self {
        Self {
            subject: AtomTerm::Variable,
            predicate_term,
            predicate_variable: false,
            object: AtomTerm::Variable,
            object_range: None,
            object_kind: ObjectKindFilter::Any,
            subject_object_equal: false,
            source: ColumnSource::Materialized,
        }
    }

    /// Point this atom at a specific committed column set (materialized head, or the layer's
    /// own additions / removals delta file). The default is [`ColumnSource::Materialized`].
    pub fn with_source(mut self, source: ColumnSource) -> Self {
        self.source = source;
        self
    }

    /// Attach a numeric object-value range filter to this atom (the object must be a
    /// `Variable`; enforced at prove/verify by `validate_atom`).
    pub fn with_object_range(mut self, range: ObjectRangeSpec) -> Self {
        self.object_range = Some(range);
        self
    }

    pub fn with_object_kind(mut self, kind: ObjectKindFilter) -> Self {
        self.object_kind = kind;
        self
    }
}

/// The additional authenticated selection and table-domain intersection used when an
/// object range has a second bound.
#[derive(Clone, Debug)]
pub struct SecondRangeSubproof {
    pub object_range: ObjectRangeProof,
    pub com_range_sel_at_d: ArkGT,
    pub relocate_range_sel: RelocationProof,
    pub com_range_sel_at_table: ArkGT,
    pub intersect: BooleanProductProof,
    pub com_intersection_sel: ArkGT,
}

/// A layer BGP plan: a relational plan has `k` atoms and `k - 1` left-deep join steps;
/// an all-ground zero-arity conjunction has no keyed joins. `joins[j]` names
/// the first shared variable's column on the evolving accumulator (`acc_key`) and on
/// atom `j + 1`'s relation (`rel_key`), plus any further shared key pairs. Each atom
/// relation has ONE column per distinct VARIABLE (in S,P,O order).
#[derive(Clone, Debug)]
pub struct LayerBgpPlan {
    pub atoms: Vec<LayerBgpAtom>,
    pub joins: Vec<JoinStep>,
    /// The plan DEFAULT column source. Each atom now carries its OWN [`LayerBgpAtom::source`]
    /// (which drives the columns/commitments/count that atom's filter reads), so this field is
    /// no longer the single source of every atom. It remains load-bearing in three ways:
    ///   * the transcript baseline — an atom whose source equals `plan.source` emits NO per-atom
    ///     source tag, so a UNIFORM plan (every atom == `plan.source`, whether all-Materialized
    ///     or all-delta) is byte-identical to the pre-per-atom encoding;
    ///   * the domain of the all-ground UNIT column and the dictionary-absence zero column
    ///     (neither reads a specific atom's relation);
    ///   * backward-compat construction ([`LayerBgpPlan::with_source`] / `materialized`).
    /// The compiler sets it to the uniform source when every atom agrees, else `Materialized`.
    /// Bound (with every atom's source) by the verifier's trusted plan reconstruction AND the
    /// Fiat–Shamir transcript. Defaults to [`ColumnSource::Materialized`].
    pub source: ColumnSource,
}

impl LayerBgpPlan {
    /// A plan over the complete materialized head view (the pre-delta default).
    pub fn materialized(atoms: Vec<LayerBgpAtom>, joins: Vec<JoinStep>) -> Self {
        Self::with_source(atoms, joins, ColumnSource::Materialized)
    }

    /// A plan whose atoms ALL read one `source` (materialized, additions, or removals). The
    /// source is propagated to EVERY atom (each atom now carries its own source, which is what
    /// prove/verify read), so this remains the single-source constructor: an all-atoms-`source`
    /// plan equals `plan.source == source`, keeping its transcript byte-identical to the
    /// pre-per-atom encoding. A cross-source plan is built by setting per-atom
    /// [`LayerBgpAtom::source`] directly (see [`LayerBgpAtom::with_source`]).
    pub fn with_source(
        mut atoms: Vec<LayerBgpAtom>,
        joins: Vec<JoinStep>,
        source: ColumnSource,
    ) -> Self {
        for atom in &mut atoms {
            atom.source = source;
        }
        Self { atoms, joins, source }
    }
}

/// The DATATYPE-HOMOGENEITY guard sub-proof for a numeric range atom (fail-closed fidelity).
/// A numeric range/order/aggregate over a datatype-HETEROGENEOUS column reject-closes: we
/// cannot faithfully match TerminusDB's cross-datatype comparison (rational siblings compared
/// by value, rational-vs-float errors, and NON-numeric rows reaching Prolog structural
/// `compare/3` — which can INCLUDE a string/node the exact-numeric mask drops), so we REFUSE
/// rather than under-report. Homogeneous (schema-constrained) data is unaffected. The atom's
/// authenticated `dt_match` column (`object_range.com_dt_match`, at `D`) is relocated to the
/// table domain; the guard proves `Com(equality_sel ⊙ (1 − dt_match)) == Com(0)` — i.e. EVERY
/// predicate-matched real row carries the pinned datatype.
#[derive(Clone, Debug)]
pub struct RangeDatatypeGuardProof {
    /// `dt_match` relocated from the dict domain `D` to the table domain.
    pub relocate_dt_match: RelocationProof,
    pub com_dt_match_at_table: ArkGT,
    /// `equality_sel ⊙ (1 − dt_match)`; verification asserts its commitment is `Com(0)`.
    pub bad: BooleanProductProof,
    pub com_bad: ArkGT,
}

/// The composed sub-proofs for a RANGED atom `t(?s, <p>, ?a) [?a op c]`: the object
/// column and the three node/value dictionary columns relocated to a common
/// power-of-two domain `D = 2^max(a, dict_log)` (each tied to its root-bound original),
/// the authenticated object-range selection at `D`, the range selection relocated back
/// to the table domain, the constant-equality selection, their product (the combined
/// selection), and the compaction of the kept columns by that combined selection.
/// `d_log`/`n_dict` are re-derived by the verifier from the (root-verified) layer, so
/// they are NOT carried here; every commitment below is authenticated against a
/// root-bound source (the relocations) or the shared transcript.
#[derive(Clone, Debug)]
pub struct RangeAtomSubproof {
    /// Object column (table -> D) + the three dict columns (dict -> D) relocations.
    pub relocate_object: RelocationProof,
    pub relocate_dict_id: RelocationProof,
    pub relocate_dict_value: RelocationProof,
    pub relocate_dict_datatype: RelocationProof,
    /// The relocated copies at domain `D` (targets; sources are root-bound).
    pub com_object_at_d: ArkGT,
    pub com_dict_id_at_d: ArkGT,
    pub com_dict_value_at_d: ArkGT,
    pub com_dict_datatype_at_d: ArkGT,
    /// The authenticated object-range selection at `D` and its `Com(range_sel)`.
    pub object_range: ObjectRangeProof,
    pub com_range_sel_at_d: ArkGT,
    /// `range_sel` relocated from `D` back to the table domain, and its commitment.
    pub relocate_range_sel: RelocationProof,
    pub com_range_sel_at_table: ArkGT,
    /// Present exactly when the public range spec carries a second bound.
    pub second: Option<SecondRangeSubproof>,
    /// The constant-equality selection (predicate + any subject constant) and `Com(sel)`.
    pub equality: SelectionOnlyProof,
    pub com_equality_sel: ArkGT,
    /// NUMERIC-FAMILY datatype guard (fail-closed fidelity) — present ONLY for a GENUINE numeric
    /// range atom that pins a numeric datatype and masks to it (`ObjectKindFilter::Any` + a
    /// numeric `object_range`). `None` for object-KIND filters (`Node`/`Literal`, which reach
    /// this same code path via a synthetic `node_kind_range`): those are datatype-agnostic —
    /// they faithfully return every matching row regardless of datatype — so no reject-close
    /// applies. The presence is fixed by the PUBLIC atom (its `object_kind` + `object_range`),
    /// reconstructed identically by the verifier, so a prover cannot skip an enforced guard.
    pub datatype_guard: Option<RangeDatatypeGuardProof>,
    /// The product `combined_sel = equality_sel · range_sel` and its commitment.
    pub combine: BooleanProductProof,
    pub com_combined_sel: ArkGT,
    /// The compaction of the kept columns by `combined_sel` (kept commitments live on the
    /// enclosing [`LayerBgpAtomProof`]).
    pub compaction: CompactionOnlyProof,
    /// Merkle-dict I2b step 3 (value↔term consistency, TERM-LESS range). The real object
    /// ids of this atom's source rows (`oid[i]` = the object id at row `i`, length = the
    /// atom's real row count `n`), and one positional Merkle opening per DISTINCT id
    /// (node/value namespace). EMPTY / `None` on a TERM-BEARING artifact (the catalog re-MSM
    /// ties value/datatype to real terms; the verifier ignores these). On a TERM-LESS
    /// artifact the verifier recommits `oid` to `com_object_at_d` (binding the touched set)
    /// and rederives `com_v_val`/`com_v_dt` from the Merkle-authenticated opened terms
    /// (`verify_dict_value_terms`). UNCOMMITTED — never folded into
    /// `commitment_root`/`resolution_root`; every opening is re-checked at verify, a missing
    /// opening (or recommit mismatch) fails closed.
    pub oid: Vec<u64>,
    pub value_openings: Option<ResolutionOpenings>,
}

/// The per-atom half of a layer BGP proof: an optional dictionary binding for a constant
/// predicate IRI, optional subject/object CONSTANT bindings (node/value dictionary), the
/// per-atom selection (EITHER a plain constant `filter` OR a `range` subproof, matching
/// the plan atom), one commitment per kept column (in S,P,O order), the result length, and
/// the REVEALED subject/object constant ids. Those ids are public inputs to verification:
/// the verifier feeds the SAME id to both the membership check (constant -> id) and the
/// filter's constant, so a prover cannot authenticate one id and filter on another.
/// Exactly one of `filter`/`range` is `Some`, determined by the PLAN atom's
/// `object_range` (never by the prover-supplied proof).
#[derive(Clone, Debug)]
pub struct LayerBgpAtomProof {
    pub predicate_membership: Option<DictProof>,
    pub subject_membership: Option<DictProof>,
    pub object_membership: Option<DictProof>,
    pub filter: Option<AtomFilterProof>,
    pub range: Option<RangeAtomSubproof>,
    pub kept_commitments: Vec<ArkGT>,
    pub m: usize,
    pub subject_id: Option<u64>,
    pub object_id: Option<u64>,
}

/// A complete k-atom layer BGP proof: one per-atom (membership + filter) proof, plus the
/// left-deep binary-join chain over the filtered relations when `k >= 2`, all under one
/// transcript. A single-atom query needs no join proof: its complete filtered relation is
/// already the complete query result.
#[derive(Clone, Debug)]
pub struct LayerBgpProof {
    pub atoms: Vec<LayerBgpAtomProof>,
    pub chain: Option<BgpChainProof>,
    /// The whole BGP is empty because a constant in one atom is absent from a
    /// root-authenticated dictionary. No row-filter or join proof is needed: a triple
    /// containing a dictionary-absent term cannot exist, so its conjunction cannot have
    /// a solution. The atom index and position make the public claim unambiguous.
    pub dictionary_absence: Option<DictionaryAbsence>,
    /// Merkle-dict I2b S5: the UNCOMMITTED term-less resolution witness. A base/rollup proof
    /// destined for a TERM-LESS artifact ships one positional [`DictOpening`] per DISTINCT
    /// matched-constant id (the S4 belt-hash) and per DISTINCT resolved-result id (S3
    /// resolution); a TERM-BEARING proof carries `None` (the catalog re-MSM supplies term
    /// fidelity, and resolution rebuilds the tree). NEVER folded into
    /// `commitment_root`/`resolution_root` — every consumer re-runs `verify_opening` against the
    /// trusted root, and a term-less proof reaching `verify_layer_bgp` WITHOUT it fails closed.
    pub openings: Option<ResolutionOpenings>,
}

/// The public claim behind an empty-because-absent BGP: the atom (`atom_index`) and the term
/// position whose constant is missing from a root-authenticated dictionary. A triple carrying a
/// dictionary-absent term cannot exist, so the whole conjunction is provably empty (see
/// [`LayerBgpProof::dictionary_absence`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DictionaryAbsence {
    pub atom_index: usize,
    pub position: DictionaryAbsencePosition,
}

/// Which term position of the atom carries the dictionary-absent constant.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DictionaryAbsencePosition {
    Predicate,
    Subject,
    Object,
}

/// Prover-side BGP output including the values bound by the result commitments. Columns
/// are padded to `2^result_log_domain`; query rows occupy `[0, result_len)`.
pub struct LayerBgpResult {
    pub proof: LayerBgpProof,
    pub result_commitments: Vec<ArkGT>,
    pub result_columns: Vec<Vec<ArkFr>>,
    pub result_log_domain: usize,
    pub result_len: usize,
    pub predicate_ids: Vec<u64>,
}

impl LayerBgpResult {
    /// Copy the real result prefix, omitting commitment-domain padding.
    pub fn real_columns(&self) -> Vec<Vec<ArkFr>> {
        self.result_columns
            .iter()
            .map(|column| column[..self.result_len].to_vec())
            .collect()
    }
}

/// The resolved dictionary ids for one atom's constants. Each id is `Some` exactly when
/// that position is a constant.
#[derive(Clone, Copy, Debug)]
pub(super) struct AtomIds {
    pub(super) predicate_id: Option<u64>,
    pub(super) subject_id: Option<u64>,
    pub(super) object_id: Option<u64>,
}

/// The canonical dictionary object a constant term resolves through, or `None` for a
/// variable. A node IRI (subject or object) resolves through `Node(iri)`; a typed literal
/// through `Value{..}` — both share the node/value id space via `hash_object`.
pub(super) fn atom_term_object(term: &AtomTerm) -> Option<CanonicalObject> {
    match term {
        AtomTerm::Variable => None,
        AtomTerm::NodeConstant(iri) => Some(CanonicalObject::Node(iri.clone())),
        AtomTerm::ValueConstant(datatype, lexical) => Some(CanonicalObject::Value {
            datatype: *datatype,
            lexical: lexical.clone(),
        }),
    }
}

/// Resolve a subject/object CONSTANT to its node/value dictionary id in this layer, or
/// fail closed if the constant is absent (except for the standalone-ground shortcut).
/// Subjects share the node/value id space with node objects, so
/// the same `(hash_object(term), id)` row authenticates the constant in either position.
pub(super) fn resolve_node_value_id(layer: &LayerCommitment, object: &CanonicalObject) -> io::Result<u64> {
    layer
        .node_value_catalog
        .iter()
        .find(|record| &record.triple.object == object)
        .map(|record| record.object_id)
        .ok_or_else(|| invalid("constant not in layer node/value dictionary"))
}

/// Enforce the atom constraints: the subject is a variable or a node constant (never a
/// value literal). Fully-ground atoms are valid here; [`validate_bgp_plan`] allows them
/// only when every atom is ground, because mixed boolean/relation composition is separate.
pub(super) fn validate_atom(atom: &LayerBgpAtom) -> io::Result<()> {
    if atom.predicate_variable != atom.predicate_term.is_empty() {
        return Err(invalid(
            "predicate variable must have an empty term and predicate constant must not",
        ));
    }
    if matches!(atom.subject, AtomTerm::ValueConstant(..)) {
        return Err(invalid(
            "layer BGP subject may not be a value-literal constant",
        ));
    }
    if let Some(range) = &atom.object_range {
        // A ranged object must be a KEPT variable — never a constant (a range on a
        // fixed object is a compile-time-true/false, out of v1 scope).
        if !matches!(atom.object, AtomTerm::Variable) {
            return Err(invalid("layer BGP object range requires a variable object"));
        }
        if !(1..=252).contains(&range.b_bits) {
            return Err(invalid(
                "layer BGP object range bit-width out of range (need 1 <= B <= 252)",
            ));
        }
    }
    if atom.object_kind != ObjectKindFilter::Any {
        if !matches!(atom.object, AtomTerm::Variable) || atom.object_range.is_some() {
            return Err(invalid(
                "object-kind filter requires an unconstrained variable object",
            ));
        }
    }
    if atom.subject_object_equal
        && (!matches!(atom.subject, AtomTerm::Variable)
            || !matches!(atom.object, AtomTerm::Variable))
    {
        return Err(invalid(
            "subject/object equality requires two variable positions",
        ));
    }
    Ok(())
}

/// The `(constant/id)` presence carried in a proof MUST match the atom's constant
/// structure: a variable position has no id, a constant position has one. Rejects a
/// malformed proof that, e.g., claims a subject id for a variable subject (which would
/// otherwise silently reshape the filter spec).
pub(super) fn check_ids_consistent(atom: &LayerBgpAtom, ids: &AtomIds) -> io::Result<()> {
    if atom.predicate_variable != ids.predicate_id.is_none() {
        return Err(invalid(
            "layer BGP predicate constant/id presence does not match the plan",
        ));
    }
    let subject_is_constant = !matches!(atom.subject, AtomTerm::Variable);
    let object_is_constant = !matches!(atom.object, AtomTerm::Variable);
    if subject_is_constant != ids.subject_id.is_some()
        || object_is_constant != ids.object_id.is_some()
    {
        return Err(invalid(
            "layer BGP atom constant/id presence does not match the plan",
        ));
    }
    Ok(())
}

/// The atom's [`AtomFilterSpec`] from its resolved ids. Constant positions carry their
/// authenticated IDs; variable positions are retained in S,P,O order. The constant list
/// order (P, then S, then O) is fixed and identical on both sides.
pub(super) fn atom_filter_spec(atom: &LayerBgpAtom, ids: &AtomIds) -> AtomFilterSpec {
    let mut constants = Vec::new();
    if let Some(predicate_id) = ids.predicate_id {
        constants.push((Position::P, ArkFr::from_u64(predicate_id)));
    }
    if let Some(subject_id) = ids.subject_id {
        constants.push((Position::S, ArkFr::from_u64(subject_id)));
    }
    if let Some(object_id) = ids.object_id {
        constants.push((Position::O, ArkFr::from_u64(object_id)));
    }
    let mut kept = Vec::new();
    if matches!(atom.subject, AtomTerm::Variable) {
        kept.push(Position::S);
    }
    if atom.predicate_variable {
        kept.push(Position::P);
    }
    if matches!(atom.object, AtomTerm::Variable) {
        kept.push(Position::O);
    }
    let equalities = if atom.subject_object_equal {
        kept.retain(|position| *position != Position::O);
        vec![(Position::S, Position::O)]
    } else {
        Vec::new()
    };
    AtomFilterSpec {
        constants,
        kept,
        equalities,
    }
}

/// Bind one atom term (subject or object) plus its optional resolved id into the shared
/// transcript: a domain-separated tag per variant (variable / node / value) and, for a
/// constant, the term bytes and revealed id. Identical on both sides.
fn bind_atom_term(transcript: &mut Transcript254, term: &AtomTerm, id: Option<u64>) {
    match term {
        AtomTerm::Variable => transcript.append_bytes(b"pow/bgp-layer/term-variable", &[]),
        AtomTerm::NodeConstant(iri) => transcript.append_bytes(b"pow/bgp-layer/term-node", iri),
        AtomTerm::ValueConstant(datatype, lexical) => {
            transcript.append_bytes(b"pow/bgp-layer/term-value-dt", &[*datatype as u8]);
            transcript.append_bytes(b"pow/bgp-layer/term-value-lex", lexical);
        }
    }
    if let Some(id) = id {
        transcript.append_bytes(b"pow/bgp-layer/term-id", &id.to_le_bytes());
    }
}

/// Bind the public statement of a layer BGP: the trust anchor (`commitment_root`, which
/// binds the column, predicate-dictionary AND node/value-dictionary commitments), `k`, and
/// every atom's subject term, predicate variant/term/optional id, and object term (each
/// constant carrying its revealed id), then the join plan. Identical on both sides.
pub(super) fn bind_layer_bgp_statement(
    transcript: &mut Transcript254,
    source: &impl VerifierLayer,
    plan: &LayerBgpPlan,
    atom_ids: &[AtomIds],
) {
    let layer = source.verifier_view();
    transcript.append_bytes(
        b"pow/bgp-layer/commitment-root",
        &layer.state.commitment_root,
    );
    // Domain-separate the plan-DEFAULT column source. `Materialized` emits NOTHING, so every
    // pre-delta transcript is byte-for-byte unchanged; a UNIFORM delta plan emits ONE tag here
    // (its atoms then match this default and emit nothing per-atom, keeping single-source delta
    // transcripts byte-identical too). A MIXED plan sets `plan.source = Materialized` (nothing
    // here) and tags only the atoms that diverge, below.
    match plan.source {
        ColumnSource::Materialized => {}
        ColumnSource::Additions => {
            transcript.append_bytes(b"pow/bgp-layer/source-additions", &[])
        }
        ColumnSource::Removals => {
            transcript.append_bytes(b"pow/bgp-layer/source-removals", &[])
        }
    }
    transcript.append_bytes(b"pow/bgp-layer/k", &(plan.atoms.len() as u64).to_le_bytes());
    for (atom, ids) in plan.atoms.iter().zip(atom_ids.iter()) {
        // PER-ATOM source override. Emitted ONLY when this atom reads a source OTHER than the
        // plan default, so a uniform plan (every atom == `plan.source`) emits nothing here and
        // its transcript is byte-identical to the pre-per-atom single-source encoding. A
        // cross-source atom emits a distinct tag (including `Materialized`-as-override, which
        // means "differs from a non-Materialized default"), domain-separating the mixed
        // statement so no two source assignments share Fiat–Shamir challenges. Anti-substitution
        // does NOT rest on this tag alone: the verifier reconstructs `plan.source` AND each
        // `atom.source` from its own trusted plan (fixed by `plan_digest`) and sources the
        // columns/count each filter opens against accordingly.
        if atom.source != plan.source {
            match atom.source {
                ColumnSource::Materialized => {
                    transcript.append_bytes(b"pow/bgp-layer/atom-source-materialized", &[])
                }
                ColumnSource::Additions => {
                    transcript.append_bytes(b"pow/bgp-layer/atom-source-additions", &[])
                }
                ColumnSource::Removals => {
                    transcript.append_bytes(b"pow/bgp-layer/atom-source-removals", &[])
                }
            }
        }
        bind_atom_term(transcript, &atom.subject, ids.subject_id);
        transcript.append_bytes(
            b"pow/bgp-layer/pred-variable",
            &[u8::from(atom.predicate_variable)],
        );
        transcript.append_bytes(b"pow/bgp-layer/pred-term", &atom.predicate_term);
        if let Some(predicate_id) = ids.predicate_id {
            transcript.append_bytes(b"pow/bgp-layer/pred-id", &predicate_id.to_le_bytes());
        }
        bind_atom_term(transcript, &atom.object, ids.object_id);
        transcript.append_bytes(
            b"pow/bgp-layer/subject-object-equal",
            &[u8::from(atom.subject_object_equal)],
        );
        // Pin the optional object range (op, datatype T, constant c, bit-width) so the
        // whole comparison is part of the statement the challenges depend on.
        match &atom.object_range {
            None => transcript.append_bytes(b"pow/bgp-layer/obj-range-none", &[]),
            Some(range) => {
                let op_tag: u8 = match range.op {
                    RangeOp::Lt => 0,
                    RangeOp::Le => 1,
                    RangeOp::Gt => 2,
                    RangeOp::Ge => 3,
                };
                transcript.append_bytes(b"pow/bgp-layer/obj-range-op", &[op_tag]);
                transcript.append_field(b"pow/bgp-layer/obj-range-dt", &range.datatype);
                transcript.append_field(b"pow/bgp-layer/obj-range-c", &range.c);
                transcript.append_bytes(
                    b"pow/bgp-layer/obj-range-bbits",
                    &(range.b_bits as u64).to_le_bytes(),
                );
                match &range.second {
                    None => transcript.append_bytes(b"pow/bgp-layer/obj-range-second-none", &[]),
                    Some(second) => {
                        let op_tag: u8 = match second.op {
                            RangeOp::Lt => 0,
                            RangeOp::Le => 1,
                            RangeOp::Gt => 2,
                            RangeOp::Ge => 3,
                        };
                        transcript.append_bytes(b"pow/bgp-layer/obj-range-second-op", &[op_tag]);
                        transcript.append_field(b"pow/bgp-layer/obj-range-second-c", &second.c);
                    }
                }
            }
        }
        let object_kind_tag = match atom.object_kind {
            ObjectKindFilter::Any => 0,
            ObjectKindFilter::Node => 1,
            ObjectKindFilter::Literal => 2,
        };
        transcript.append_bytes(b"pow/bgp-layer/object-kind", &[object_kind_tag]);
    }
    for step in &plan.joins {
        transcript.append_bytes(
            b"pow/bgp-layer/acc-key",
            &(step.acc_key as u64).to_le_bytes(),
        );
        transcript.append_bytes(
            b"pow/bgp-layer/rel-key",
            &(step.rel_key as u64).to_le_bytes(),
        );
        transcript.append_bytes(
            b"pow/bgp-layer/additional-key-count",
            &(step.additional_keys.len() as u64).to_le_bytes(),
        );
        for (acc_key, rel_key) in &step.additional_keys {
            transcript.append_bytes(
                b"pow/bgp-layer/additional-acc-key",
                &(*acc_key as u64).to_le_bytes(),
            );
            transcript.append_bytes(
                b"pow/bgp-layer/additional-rel-key",
                &(*rel_key as u64).to_le_bytes(),
            );
        }
    }
}

pub(super) fn validate_bgp_plan(plan: &LayerBgpPlan) -> io::Result<usize> {
    let k = plan.atoms.len();
    if k == 0 {
        return Err(invalid("layer BGP needs at least one atom"));
    }
    for atom in &plan.atoms {
        validate_atom(atom)?;
    }
    let ground_count = plan
        .atoms
        .iter()
        .filter(|atom| {
            !atom.predicate_variable
                && !matches!(atom.subject, AtomTerm::Variable)
                && !matches!(atom.object, AtomTerm::Variable)
        })
        .count();
    if ground_count == k {
        if !plan.joins.is_empty() {
            return Err(invalid("all-ground BGP must not carry keyed join steps"));
        }
    } else {
        let relational_count = k - ground_count;
        if plan.atoms[..relational_count].iter().any(atom_is_ground)
            || plan.atoms[relational_count..]
                .iter()
                .any(|atom| !atom_is_ground(atom))
        {
            return Err(invalid(
                "mixed BGP must place every ground atom after relational atoms",
            ));
        }
        if plan.joins.len() != relational_count - 1 {
            return Err(invalid(
                "relational BGP prefix must have exactly k-1 join steps",
            ));
        }
    }
    result_id_namespaces(plan)?;
    Ok(k)
}

fn atom_is_ground(atom: &LayerBgpAtom) -> bool {
    !atom.predicate_variable
        && !matches!(atom.subject, AtomTerm::Variable)
        && !matches!(atom.object, AtomTerm::Variable)
}

pub(super) fn relational_atom_count(plan: &LayerBgpPlan) -> usize {
    plan.atoms.iter().take_while(|atom| !atom_is_ground(atom)).count()
}

pub(super) fn is_all_ground(plan: &LayerBgpPlan) -> bool {
    !plan.atoms.is_empty() && relational_atom_count(plan) == 0
}

/// Whether the plan's sole result column is the filter gadget's internal UNIT column.
/// It authenticates a zero-arity relation's cardinality but is not a Store dictionary ID.
pub(crate) fn has_ground_result_unit(plan: &LayerBgpPlan) -> bool {
    !plan.atoms.is_empty() && is_all_ground(plan)
}

/// The FIRST constant of `plan` (atom order; predicate, subject, object within an atom) that the
/// layer's dictionaries omit, or `None` when every constant is present. TERM-BEARING: the catalog
/// scans. ATTESTED term-less: one term-sorted index opening per constant up to and including the
/// first absent one (membership or a bracketing absence pair). BARE term-less: `Err`.
pub(super) fn dictionary_absence(
    source: &impl VerifierLayer,
    plan: &LayerBgpPlan,
) -> io::Result<Option<DictionaryAbsence>> {
    for (atom_index, atom) in plan.atoms.iter().enumerate() {
        if !atom.predicate_variable
            && crate::proof::commitment::predicate_term_id(source, &atom.predicate_term)?.is_none()
        {
            return Ok(Some(DictionaryAbsence {
                atom_index,
                position: DictionaryAbsencePosition::Predicate,
            }));
        }
        if let Some(subject) = atom_term_object(&atom.subject) {
            if crate::proof::commitment::node_value_term_id(source, &subject)?.is_none() {
                return Ok(Some(DictionaryAbsence {
                    atom_index,
                    position: DictionaryAbsencePosition::Subject,
                }));
            }
        }
        if let Some(object) = atom_term_object(&atom.object) {
            if crate::proof::commitment::node_value_term_id(source, &object)?.is_none() {
                return Ok(Some(DictionaryAbsence {
                    atom_index,
                    position: DictionaryAbsencePosition::Object,
                }));
            }
        }
    }
    Ok(None)
}
